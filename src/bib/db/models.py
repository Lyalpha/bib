"""SQLAlchemy ORM models — the full bib schema.

Sized for the complete BPASS release; the golden subset only fills part of it.
Array-like data (SED fluxes, filter curves, HRD grids, wavelength axes) is
stored as raw little-endian float bytes (``bytea``) and decoded with
``numpy.frombuffer`` — see ``bib.science.sed``.

Conventions
-----------
- ``age_index`` (0–50) maps to log(age/yr) = 6.0 + 0.1 * age_index, the BPASS
  population age grid. ``log_age`` is stored alongside for convenience.
- String enums are plain ``VARCHAR`` + CHECK constraints (simpler migrations
  than native PG enums).
- ``is_synthetic`` marks demo data generated by ``bib demo-seed``; the UI shows
  a warning banner whenever any synthetic rows exist.
"""

from __future__ import annotations

import datetime
from typing import Any

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    Float,
    ForeignKey,
    Index,
    LargeBinary,
    MetaData,
    SmallInteger,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, declared_attr, mapped_column, relationship

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {  # noqa: RUF012 — SQLAlchemy class-level configuration
        float: Float(53),  # double precision
        dict[str, Any]: JSONB,
    }


# ---------------------------------------------------------------------------
# Releases, wavelength grids, populations
# ---------------------------------------------------------------------------


class Release(Base):
    """A BPASS data release (e.g. v2.2.1 'Tuatara', v2.3)."""

    __tablename__ = "release"

    id: Mapped[int] = mapped_column(primary_key=True)
    version: Mapped[str] = mapped_column(String(16), unique=True)
    name: Mapped[str | None] = mapped_column(String(64))
    citation: Mapped[str | None] = mapped_column(Text)
    url: Mapped[str | None] = mapped_column(String(256))
    notes: Mapped[str | None] = mapped_column(Text)

    populations: Mapped[list[Population]] = relationship(back_populates="release")


class WavelengthGrid(Base):
    """A shared wavelength axis (float64 Å), stored once per distinct grid."""

    __tablename__ = "wavelength_grid"

    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(64), unique=True)
    kind: Mapped[str] = mapped_column(
        String(16), default="native"
    )  # 'native' (full resolution) or 'display' (downsampled)
    n_points: Mapped[int]
    unit: Mapped[str] = mapped_column(String(16), default="angstrom")
    data: Mapped[bytes] = mapped_column(LargeBinary)  # float64 little-endian

    __table_args__ = (CheckConstraint("kind IN ('native', 'display')", name="kind_valid"),)


class Population(Base):
    """One simple stellar population grid = one BPASS spectra file.

    Identified by (release, IMF, metallicity, sin/bin, alpha-enhancement).
    ``alpha_label`` is NULL for v2.2.1 populations and one of
    a-02/a+00/a+02/a+04/a+06 for v2.3.
    """

    __tablename__ = "population"

    id: Mapped[int] = mapped_column(primary_key=True)
    release_id: Mapped[int] = mapped_column(ForeignKey("release.id", ondelete="CASCADE"))
    imf: Mapped[str] = mapped_column(String(32), index=True)
    z_label: Mapped[str] = mapped_column(String(8))
    z_value: Mapped[float] = mapped_column(index=True)
    pop_type: Mapped[str] = mapped_column(String(3))
    alpha_label: Mapped[str | None] = mapped_column(String(8))
    alpha_value: Mapped[float | None]

    native_grid_id: Mapped[int | None] = mapped_column(ForeignKey("wavelength_grid.id"))
    display_grid_id: Mapped[int | None] = mapped_column(ForeignKey("wavelength_grid.id"))

    source_file: Mapped[str | None] = mapped_column(String(256))
    sha256: Mapped[str | None] = mapped_column(String(64))
    ingested_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    is_synthetic: Mapped[bool] = mapped_column(default=False)
    extra: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict)

    release: Mapped[Release] = relationship(back_populates="populations")
    native_grid: Mapped[WavelengthGrid | None] = relationship(foreign_keys=[native_grid_id])
    display_grid: Mapped[WavelengthGrid | None] = relationship(foreign_keys=[display_grid_id])

    __table_args__ = (
        CheckConstraint("pop_type IN ('sin', 'bin')", name="pop_type_valid"),
        UniqueConstraint(
            "release_id",
            "imf",
            "z_label",
            "pop_type",
            "alpha_label",
            name="population_identity",
            postgresql_nulls_not_distinct=True,
        ),
    )


