class StellarModel(Base):
    """One detailed stellar evolution model (a BPASS ``sneplot`` file).

    kind:
      - 'single'    — single star (NEWSINMODS)
      - 'primary'   — binary primary, filename sneplot-<z>-M1-q-logP
      - 'secondary' — post-primary-death system, sneplot_2-<z>-M2-Mrem-logP
    """

    __tablename__ = "stellar_model"

    id: Mapped[int] = mapped_column(primary_key=True)
    z_label: Mapped[str] = mapped_column(String(8))
    z_value: Mapped[float] = mapped_column(index=True)
    kind: Mapped[str] = mapped_column(String(12), index=True)
    filename: Mapped[str] = mapped_column(String(128))

    m1_init: Mapped[float | None] = mapped_column(index=True)  # initial mass of tracked star
    q_init: Mapped[float | None]  # M2/M1 (primaries)
    logp_init: Mapped[float | None] = mapped_column(index=True)  # log10(P/days)
    mrem_init: Mapped[float | None]  # remnant companion mass (secondaries)

    n_steps: Mapped[int] = mapped_column(default=0)
    final_mass: Mapped[float | None]  # summary for query building
    curated: Mapped[bool] = mapped_column(default=False)
    title: Mapped[str | None] = mapped_column(String(160))
    description: Mapped[str | None] = mapped_column(Text)

    source_file: Mapped[str | None] = mapped_column(String(256))
    sha256: Mapped[str | None] = mapped_column(String(64))
    ingested_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now()
    )
    is_synthetic: Mapped[bool] = mapped_column(default=False)
    extra: Mapped[dict[str, Any]] = mapped_column(JSONB, default=dict)

    steps: Mapped[list[StellarModelStep]] = relationship(
        back_populates="model",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by="StellarModelStep.step",
    )
    events: Mapped[list[ModelEvent]] = relationship(
        back_populates="model",
        cascade="all, delete-orphan",
        passive_deletes=True,
        order_by="ModelEvent.step",
    )

    __table_args__ = (
        CheckConstraint("kind IN ('single', 'primary', 'secondary')", name="kind_valid"),
        UniqueConstraint("z_label", "filename", name="model_identity"),
    )


class StellarModelStep(Base):
    """One timestep of a stellar model (subset of manual columns 1–52).

    Mass-transfer/wind rate columns (dm*) are the raw code values — ambiguous
    absolute units, used as flags/relative intensities. Physical mass-loss
    rates for display are derived from finite differences of mass vs age.
    Companion log_r2/log_t2/log_l2 are estimates and may be absent.
    """

    __tablename__ = "stellar_model_step"

    model_id: Mapped[int] = mapped_column(
        ForeignKey("stellar_model.id", ondelete="CASCADE"), primary_key=True
    )
    step: Mapped[int] = mapped_column(primary_key=True)

    age_yr: Mapped[float]
    log_r1: Mapped[float]
    log_t1: Mapped[float]
    log_l1: Mapped[float]
    m1: Mapped[float]
    he_core: Mapped[float]
    co_core: Mapped[float]
    one_core: Mapped[float]

    x_surf: Mapped[float]
    y_surf: Mapped[float]
    c_surf: Mapped[float]
    n_surf: Mapped[float]
    o_surf: Mapped[float]
    ne_surf: Mapped[float]

    dm1w: Mapped[float | None]
    dm2w: Mapped[float | None]
    dm1a: Mapped[float | None]
    dm2a: Mapped[float | None]
    dm1r: Mapped[float | None]
    dm2r: Mapped[float | None]

    period_yr: Mapped[float | None]
    log_sep: Mapped[float | None]  # log10(a / Rsun)
    m2: Mapped[float | None]
    log_r2: Mapped[float | None]
    log_t2: Mapped[float | None]
    log_l2: Mapped[float | None]

    model: Mapped[StellarModel] = relationship(back_populates="steps")


class ModelEvent(Base):
    """A named evolutionary phase/point detected at ingest (heuristic)."""

    __tablename__ = "model_event"

    id: Mapped[int] = mapped_column(primary_key=True)
    model_id: Mapped[int] = mapped_column(
        ForeignKey("stellar_model.id", ondelete="CASCADE"), index=True
    )
    event_type: Mapped[str] = mapped_column(String(32))
    step: Mapped[int]
    age_yr: Mapped[float]
    label: Mapped[str] = mapped_column(String(120))
    note: Mapped[str | None] = mapped_column(Text)

    model: Mapped[StellarModel] = relationship(back_populates="events")


