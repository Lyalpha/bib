# Per-age population products
# ---------------------------------------------------------------------------


class AgeRowMixin:
    """Row keyed by (population, age bin). log(age/yr) = 6.0 + 0.1 * age_index.

    ``sort_order`` puts these columns (and the PK) first: the btree then
    clusters by population, which matches every query we make.
    """

    @declared_attr
    def population_id(cls) -> Mapped[int]:
        return mapped_column(
            ForeignKey("population.id", ondelete="CASCADE"),
            primary_key=True,
            sort_order=-3,
        )

    age_index: Mapped[int] = mapped_column(SmallInteger, primary_key=True, sort_order=-2)
    log_age: Mapped[float] = mapped_column(sort_order=-1)


class Sed(AgeRowMixin, Base):
    """SED at one population age.

    ``flux``: float32 L_sun/Å for 10^6 M_sun formed, on the population's
    native wavelength grid (full resolution — used for photometry/downloads).
    ``flux_ds``: float32 on the display grid (used for interactive plots).
    """

    __tablename__ = "sed"

    n_points: Mapped[int]
    flux: Mapped[bytes] = mapped_column(LargeBinary)
    n_points_ds: Mapped[int]
    flux_ds: Mapped[bytes] = mapped_column(LargeBinary)
    log_lbol: Mapped[float | None]  # log10(total luminosity / Lsun), convenience


