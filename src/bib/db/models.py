class Filter(Base):
    """A bundled filter transmission curve (float64 Å / dimensionless)."""

    __tablename__ = "filter"

    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(64), unique=True)  # e.g. 'sdss.g'
    display_name: Mapped[str] = mapped_column(String(64))
    group_name: Mapped[str] = mapped_column(String(32), index=True)  # e.g. 'SDSS'
    facility: Mapped[str | None] = mapped_column(String(64))
    detector_type: Mapped[str] = mapped_column(String(8), default="photon")
    n_points: Mapped[int]
    wavelength: Mapped[bytes] = mapped_column(LargeBinary)
    transmission: Mapped[bytes] = mapped_column(LargeBinary)
    lambda_eff: Mapped[float]
    lambda_min: Mapped[float]
    lambda_max: Mapped[float]
    source: Mapped[str | None] = mapped_column(String(256))
    citation: Mapped[str | None] = mapped_column(Text)

    __table_args__ = (
        CheckConstraint("detector_type IN ('photon', 'energy')", name="detector_valid"),
    )


